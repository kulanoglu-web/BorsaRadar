    public static String[] symbols(boolean includeTuprs) {
        List<String> out = new ArrayList<>();
        for (String entry : ENTRIES) {
            String symbol = entry.substring(0, entry.indexOf(" • "));
            if (includeTuprs || !"TUPRS".equals(symbol)) out.add(symbol);
        }
        return out.toArray(new String[0]);
    }

    public static String symbolFromEntry(String value) {
        if (value == null) return "";
        String clean = value.trim().toUpperCase(java.util.Locale.ROOT);
        int split = clean.indexOf(" • ");
        return split > 0 ? clean.substring(0, split) : clean;
    }
